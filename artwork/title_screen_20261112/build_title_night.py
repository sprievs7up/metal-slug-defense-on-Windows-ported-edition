"""月夜标题画面的游戏内素材生成（2026-11-12）。
来源：MSA 7.13.0 背景 bg 159（ms7_6_base_1_out / ms7_6_base_2_out，解码结果与动作记录在 verification/ms7_m6_20261103/msa/）。
取景：图集像素 710×381 的窗口（左上角在场景 x 704），背景下移 80 行、上方补一排星空、月亮上移 110 行（试拼脚本 msa_bg159_title_mock_moon.py 的同一组函数）。
输出（custom_content/）：title_night_atlas.png（2048×1024 RGBA）、title_night.json（图块、帧、绘制设定）。
图集内各图块四周外扩 1 像素（非整数倍绘制时避免采到相邻图块）。接缝位置均取 5 的倍数（× 1.8 为整数屏幕像素，1280×720）。
用法（工作区根目录）：E:/anaconda3/python.exe -I artwork/title_screen_20261112/build_title_night.py"""
import json, runpy
from pathlib import Path
import numpy as np
from PIL import Image
V = Path('verification/title_screen_20261112')
OUT = Path('custom_content')
m = runpy.run_path(str(V / 'msa_bg159_title_mock_moon.py'))
tile, upper, blit, scripts, mask = m['tile'], m['upper'], m['blit'], m['scripts'], m['mask']
cx, cy, rad, R_OUT, dist, yy, xx = (m[k] for k in ('cx', 'cy', 'rad', 'R_OUT', 'dist', 'yy', 'xx'))
X0, N, LIFT, W, H = 704, 80, 110, 710, 381
FR = list(range(11, 20))                                 # 无月亮星空的 9 帧（动作记录帧号）


def star(f):
    t = Image.new('RGBA', (512, 256)); blit(t, f, 0, 0); return t


def strip(f):
    """上排星空：图块第 48–128 行，减去底色渐变，左右、上下翻转（同 msa_bg159_title_mock_moon.upper），取 510 列。"""
    a = np.asarray(star(f).convert('RGB')).astype(int)
    ref = np.asarray(star(FR[0]).convert('RGB')).astype(int)
    b = a[128 - N:128] - np.median(ref[128 - N:128], axis=1)[:, None, :].astype(int) + np.median(ref[0], axis=0).astype(int)
    return Image.fromarray(np.clip(b, 0, 255).astype('uint8')[::-1, ::-1]).convert('RGBA').crop((0, 0, 510, N))


assert np.array_equal(np.asarray(strip(FR[0]).convert('RGB')), np.asarray(upper(3, 0, N).convert('RGB'))[:, :510])
atlas = Image.new('RGBA', (2048, 1024))
rects = []                                              # [x, y, w, h, anchor_x, anchor_y, flag, page]；锚点 = −(窗口内位置)


def put(img, x, y):
    """贴入图集并向四周外扩 1 像素。"""
    w, h = img.size
    atlas.paste(img.resize((w + 2, h + 2), Image.NEAREST), (x - 1, y - 1))      # 先铺底（近似），再逐边复制
    atlas.paste(img.crop((0, 0, w, 1)), (x, y - 1)); atlas.paste(img.crop((0, h - 1, w, h)), (x, y + h))
    atlas.paste(img.crop((0, 0, 1, h)), (x - 1, y)); atlas.paste(img.crop((w - 1, 0, w, h)), (x + w, y))
    atlas.paste(img, (x, y))


low_cell, up_cell = {}, {}
for j, f in enumerate(FR):
    x, y = j % 3 * 514 + 1, j // 3 * 258 + 1
    put(star(f), x, y); low_cell[j] = (x, y)
    x, y = j % 3 * 514 + 1, 774 + j // 3 * 82 + 1
    put(strip(f), x, y); up_cell[j] = (x, y)
# 地面（动作记录帧 20：树林与雪地），窗口内的部分
ground = Image.new('RGBA', (2560, 420 + N)); blit(ground, 20, 0, N)
ground = ground.crop((X0, 0, X0 + W, H)); gb = ground.getbbox()
gtop = gb[1]; gh = H - gtop
gl, gr = ground.crop((0, gtop, 500, H)), ground.crop((500, gtop, W, H))
put(gl, 1545, 1); put(gr, 1545, gh + 4)
# 月亮：带月亮图块第 0 帧，月面与边缘保持原样，其外过渡到上半圈镜像光晕；圆形羽化蒙版
src = np.asarray(tile(2, 0)).astype(float)
w_ = (np.clip((dist - rad - 2) / 2, 0, 1) * (yy > cy) * (dist < R_OUT + 1))[..., None]
mir = src[np.clip(np.rint(2 * cy - yy).astype(int), 0, 255), xx]
moon = Image.fromarray((src * (1 - w_) + mir * w_ + 0.5).astype('uint8')); moon.putalpha(mask)
mb = moon.getbbox(); moon_c = moon.crop(mb)
mx, my = 1545 + 214, gh + 4
atlas.alpha_composite(moon_c, (mx, my))


def rect(x, y, w, h, wx, wy):
    rects.append([x, y, w, h, -wx, -wy, 0, 1]); return len(rects) - 1


UP = [(374 - X0, 3), (884 - X0, 0), (1394 - X0, 7)]       # 上排三块：窗口 x、起始帧（各块相位错开）
LOW = [(512 - X0, 7), (1024 - X0, 3)]                    # 下排两块（场景 x 512 / 1024，下移 N 行）
up_r = {(i, j): rect(*up_cell[j], 510, N, wx, 0) for i, (wx, _s) in enumerate(UP) for j in range(9)}
low_r = {(i, j): rect(*low_cell[j], 512, 256, wx, N) for i, (wx, _s) in enumerate(LOW) for j in range(9)}
moon_r = rect(mx, my, *moon_c.size, 1024 - X0 + mb[0], N - LIFT + mb[1])
gl_r, gr_r = rect(1545, 1, 500, gh, 0, gtop), rect(1545, gh + 4, W - 500, gh, 500, gtop)
patterns = []
for k in range(9):
    patterns.append([up_r[(i, (s + k) % 9)] for i, (_x, s) in enumerate(UP)] + [low_r[(i, (s + k) % 9)] for i, (_x, s) in enumerate(LOW)]
                    + [moon_r, gl_r, gr_r])
for wx, _s in UP[1:] + LOW[1:]:                         # 画面内的接缝（上排 180、690，下排 320）须为 5 的倍数
    assert wx % 5 == 0, wx
# 标题图层按普通透明度混合（实测月亮光晕的径向亮度与离线合成逐点一致）；图集保持非预乘的颜色。
atlas.save(OUT / 'title_night_atlas.png')
layout = {
    'note': 'generated by artwork/title_screen_20261112/build_title_night.py',
    'atlas': 'title_night_atlas.png',
    'background_scale': 1.6, 'frame_ticks': 6,
    'rects': rects, 'patterns': patterns,
    'bar_rects': [[0, 188, 512, 15, 0, -305, 0, 0], [412, 330, 56, 15, -512, -305, 0, 0]],
}
(OUT / 'title_night.json').write_text(json.dumps(layout, separators=(',', ':')) + '\n', encoding='utf-8')
print('rects', len(rects), 'ground top', gtop, 'ground h', gh, 'moon', moon_c.size, 'moon window xy', (-rects[moon_r][4], -rects[moon_r][5]))
# 自检：按布局数据重画第 0 帧，与试拼函数的同一窗口比较
chk = Image.new('RGBA', (W, H), (0, 0, 0, 255))
for r in patterns[0]:
    x, y, w, h, ax, ay, _f, _p = rects[r]
    chk.alpha_composite(atlas.crop((x, y, x + w, y + h)), (-ax, -ay)) if -ax >= 0 and -ay >= 0 else chk.paste(atlas.crop((x, y, x + w, y + h)), (-ax, -ay), atlas.crop((x, y, x + w, y + h)))
chk.save(V / 'out/title_night_layout_check.png')
